package com.abhiraj.archyra.analysis;

import java.time.Instant;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.DynamicUpdate;
import org.hibernate.annotations.UpdateTimestamp;

/**
 * Analysis metadata stored in PostgreSQL ({@code analyses} table). The code graph itself lives in
 * Neo4j and refers back to this row only by {@link #id}.
 */
@Entity
@DynamicUpdate // an entity save writes only what changed, so it can never overwrite quota_refunded, which has its own guarded UPDATE
@Table(name = "analyses", indexes = @Index(name = "idx_analysis_owner", columnList = "user_id"))
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class Analysis {

	static final int FAILURE_REASON_LENGTH = 1000;

	/** Exposed by the API as {@code analysisId}. Generated by the persistence layer on first save. */
	@Id
	@GeneratedValue(strategy = GenerationType.UUID)
	private UUID id;

	/**
	 * The user who started the analysis, and the only one who may read or delete it. Always set for new rows; null
	 * only for rows created before accounts existed, which no one can see and {@code LegacyAnalysisPurger} deletes
	 * at startup. Kept as a plain id: accounts belong to the
	 * {@code user} feature, which this one does not reach into.
	 */
	@Column(name = "user_id", updatable = false)
	private UUID ownerId;

	@Column(name = "repository_url", nullable = false, length = 200, updatable = false)
	private String repositoryUrl;

	@Enumerated(EnumType.STRING)
	@Column(nullable = false, length = 20)
	private AnalysisStatus status;

	/** Percentage complete, 0 to 100. */
	@Column(nullable = false)
	private int progress;

	/** Why the analysis ended in {@link AnalysisStatus#FAILED}; null otherwise. */
	@Column(name = "failure_reason", length = FAILURE_REASON_LENGTH)
	private String failureReason;

	/**
	 * True when creating this analysis consumed one unit of the owner's allowance. Rows from before usage tracking
	 * keep false, so they can never trigger a refund.
	 */
	@Column(name = "quota_charged", nullable = false, columnDefinition = "boolean not null default false")
	private boolean quotaCharged;

	/** True once that unit was returned. Set by one guarded UPDATE, which is what makes a refund happen only once. */
	@Column(name = "quota_refunded", nullable = false, columnDefinition = "boolean not null default false")
	private boolean quotaRefunded;

	/**
	 * Set when this analysis is a re-run of an earlier, finished one: that analysis (graph, metadata and row) is
	 * deleted once this one COMPLETES, so a failed re-run leaves the old results alone. Kept afterwards as a record;
	 * it is a plain id, so it may point at a row that is gone.
	 */
	@Column(name = "replaces_analysis_id", updatable = false)
	private UUID replacesAnalysisId;

	@CreationTimestamp
	@Column(name = "created_at", nullable = false, updatable = false)
	private Instant createdAt;

	@UpdateTimestamp
	@Column(name = "updated_at", nullable = false)
	private Instant updatedAt;

	private Analysis(String repositoryUrl, UUID ownerId) {
		this.repositoryUrl = repositoryUrl;
		this.ownerId = ownerId;
		this.status = AnalysisStatus.QUEUED;
		this.progress = 0;
	}

	/** A new analysis always starts as {@link AnalysisStatus#QUEUED} with 0% progress and belongs to {@code ownerId}. */
	public static Analysis queued(String repositoryUrl, UUID ownerId) {
		if (ownerId == null) {
			throw new IllegalArgumentException("An analysis must have an owner");
		}
		return new Analysis(repositoryUrl, ownerId);
	}

	/**
	 * A restored entry: the repository link of an analysis whose account was deleted, given back to the person who returned.
	 * It is {@link AnalysisStatus#NOT_ANALYZED}, 0%, with the credit already attached ({@code quotaCharged}, not refunded)
	 * because the restored usage count already includes it. Only the registrar creates it. Moving it to
	 * {@link AnalysisStatus#QUEUED} is the guarded UPDATE {@link AnalysisRepository#queueRestored}, which keeps
	 * {@code quotaCharged}, so two simultaneous requests start one run.
	 */
	static Analysis restored(String repositoryUrl, UUID ownerId) {
		if (ownerId == null) {
			throw new IllegalArgumentException("An analysis must have an owner");
		}
		Analysis analysis = new Analysis(repositoryUrl, ownerId);
		analysis.status = AnalysisStatus.NOT_ANALYZED;
		analysis.quotaCharged = true;
		return analysis;
	}

	/** Records that this analysis consumed a unit. Only the registrar charges, in the same transaction as the insert. */
	void markQuotaCharged() {
		this.quotaCharged = true;
	}

	/** Only the registrar sets this, before the first save. */
	void replaces(UUID analysisId) {
		this.replacesAnalysisId = analysisId;
	}

	/** COMPLETED and FAILED are final; nothing changes after them. */
	public boolean isFinished() {
		return status == AnalysisStatus.COMPLETED || status == AnalysisStatus.FAILED;
	}

	/** Queued or running: a pipeline run owns the row. A {@link AnalysisStatus#NOT_ANALYZED} entry is neither this nor finished. */
	public boolean isInProgress() {
		return status != AnalysisStatus.NOT_ANALYZED && !isFinished();
	}

	/** Moves the pipeline to the next stage. {@code progress} is a percentage from 0 to 100. */
	public void advanceTo(AnalysisStatus nextStatus, int nextProgress) {
		requireInProgress();
		if (nextStatus == AnalysisStatus.COMPLETED || nextStatus == AnalysisStatus.FAILED || nextStatus == AnalysisStatus.NOT_ANALYZED) {
			throw new IllegalArgumentException("Use markCompleted() or markFailed() to finish an analysis");
		}
		this.status = nextStatus;
		this.progress = Math.clamp(nextProgress, 0, 100);
	}

	public void markCompleted() {
		requireInProgress();
		this.status = AnalysisStatus.COMPLETED;
		this.progress = 100;
		this.failureReason = null;
	}

	/** Ends the analysis as FAILED, keeping the progress reached so far. The reason is cut to fit its column. */
	public void markFailed(String reason) {
		requireInProgress();
		this.status = AnalysisStatus.FAILED;
		this.failureReason = reason == null || reason.length() <= FAILURE_REASON_LENGTH
				? reason : reason.substring(0, FAILURE_REASON_LENGTH);
	}

	/** A pipeline only ever changes a queued or running analysis: not a finished one, and not an entry nobody started. */
	private void requireInProgress() {
		if (!isInProgress()) {
			throw new IllegalStateException("Analysis " + id + " is " + status + " and is not running");
		}
	}
}
